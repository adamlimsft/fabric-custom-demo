"""Rebuilds everything that is generated from the pack definitions in config/<pack>.json ("pack" section):

  * the control-table rows in config/<pack>.json (source_system, ingestion_object, column_map, dq_rule, gold_transform, onboard)
  * sql/source_db/<pack>.sql      - seed script for the optional "source database" (pipeline Copy demo)
  * mlv/sql/<pack>.sql            - materialized lake view DDL preview
  * the embedded copies inside notebooks nb_mdf_00, nb_mdf_01, nb_mdf_mlv_sqlgen and nb_rti_01
  * warehouse/, rti/, dataflows/ and ai/ files, when their builder scripts are present in tools/

Usage:  python tools/build_kit.py            (all packs)
        python tools/build_kit.py mining     (after you add config/mining.json - see docs/ADD_INDUSTRY.md)
Standard library only.
"""
import importlib.util, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import kitlib  # noqa: E402
import generate_data  # noqa: E402

KIT = kitlib.KIT


def _load_module(name):
    path = os.path.join(HERE, f"{name}.py")
    if not os.path.exists(path):
        return None
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def write(rel, text):
    path = os.path.join(KIT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


# ------------------------------------------------------------------------------------------ config
def build_config(p):
    path = os.path.join(KIT, "config", f"{p['id']}.json")
    doc = {"pack": p}
    doc.update(kitlib.control_rows(p))
    with open(path, "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=1, ensure_ascii=False)
    return doc


# ------------------------------------------------------------------------------------------ source database seed
def _sqlv(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "N'" + str(v).replace("'", "''") + "'"


def source_db_sql(p, data):
    E, V = p["entity"], p["event"]
    reg = p["region_col"]
    ecols = [(E["id"], "INT NOT NULL"), (E["code"], "NVARCHAR(30)"), (E["name_col"], "NVARCHAR(100)"), (E["type_col"], "NVARCHAR(30)"),
             (reg, "NVARCHAR(40)"), ("status", "NVARCHAR(30)"), (E["tier_col"], "INT"), (E["cap_col"], "DECIMAL(12,1)"),
             (E["start_col"], "DATE"), ("last_modified", "DATETIME2(0)")]
    vcols = [(V["id"], "INT NOT NULL"), (E["id"], "INT"), (V["type_col"], "NVARCHAR(30)"), ("priority", "INT"),
             ("status", "NVARCHAR(30)"), (V["open_ts"], "DATETIME2(0)"), (V["close_ts"], "DATETIME2(0)"),
             (V["amount_col"], "DECIMAL(12,2)"), (V["qty_col"], "DECIMAL(10,2)"), ("description", "NVARCHAR(200)"),
             ("last_modified", "DATETIME2(0)")]
    drift = E["drift_col"]
    en, vn = f"src.{E['src']}", f"src.{V['src']}"
    es, vs = f"src.stage_{E['src']}", f"src.stage_{V['src']}"
    L = [f"/* {p['org']} ({p['industry']}) - source database seed for the pipeline Copy demo",
         f"   Plays the role of: {p['sys']['ops']['name']}",
         "   Run this whole script ONCE in a Fabric SQL database (or Azure SQL / SQL Server). Then release the days in order:",
         "       EXEC src.usp_release_day 1;   -- before the first pipeline run",
         "       EXEC src.usp_release_day 2;   -- before the second run",
         "       EXEC src.usp_release_day 3;   -- before the third run (adds a new column = schema drift)",
         "   Generated by tools/build_kit.py - all data is fictional. */",
         "IF SCHEMA_ID('src') IS NULL EXEC('CREATE SCHEMA src');", "GO",
         f"DROP TABLE IF EXISTS {en}; DROP TABLE IF EXISTS {vn}; DROP TABLE IF EXISTS {es}; DROP TABLE IF EXISTS {vs};",
         f"CREATE TABLE {en} (" + ", ".join(f"{c} {t}" for c, t in ecols) + f", CONSTRAINT pk_{E['src']} PRIMARY KEY ({E['id']}));",
         f"CREATE TABLE {vn} (" + ", ".join(f"{c} {t}" for c, t in vcols) + f", CONSTRAINT pk_{V['src']} PRIMARY KEY ({V['id']}));",
         f"CREATE TABLE {es} (release_day INT NOT NULL, " + ", ".join(f"{c} {t.replace(' NOT NULL', '')}" for c, t in ecols) +
         f", {drift} NVARCHAR(50));",
         f"CREATE TABLE {vs} (release_day INT NOT NULL, " + ", ".join(f"{c} {t.replace(' NOT NULL', '')}" for c, t in vcols) + ");",
         "GO"]

    def inserts(table, cols, rows_by_day, extra=None):
        out = []
        names = ["release_day"] + [c for c, _ in cols] + ([extra] if extra else [])
        buf = []
        for day, rows in rows_by_day.items():
            for row in rows:
                vals = [day] + [row.get(c) for c, _ in cols] + ([row.get(extra)] if extra else [])
                buf.append("(" + ", ".join(_sqlv(v) for v in vals) + ")")
        for i in range(0, len(buf), 500):
            out.append(f"INSERT INTO {table} ({', '.join(names)}) VALUES\n" + ",\n".join(buf[i:i + 500]) + ";")
        return out
    L += inserts(es, ecols, data["entity"], drift)
    L += inserts(vs, vcols, data["event"])
    L.append("GO")
    ec = ", ".join(c for c, _ in ecols)
    vc = ", ".join(c for c, _ in vcols)
    L += [f"CREATE OR ALTER PROCEDURE src.usp_release_day @day INT",
          "AS",
          "BEGIN",
          "    SET NOCOUNT ON;",
          f"    IF @day >= 3 AND COL_LENGTH('{en}', '{drift}') IS NULL",
          f"        EXEC('ALTER TABLE {en} ADD {drift} NVARCHAR(50) NULL');",
          f"    DELETE t FROM {en} t WHERE EXISTS (SELECT 1 FROM {es} s WHERE s.release_day = @day AND s.{E['id']} = t.{E['id']});",
          f"    INSERT INTO {en} ({ec}) SELECT {ec} FROM {es} WHERE release_day = @day;",
          f"    IF @day >= 3",
          f"        EXEC('UPDATE t SET t.{drift} = s.{drift} FROM {en} t JOIN {es} s ON s.{E['id']} = t.{E['id']} AND s.release_day = 3');",
          f"    DELETE t FROM {vn} t WHERE EXISTS (SELECT 1 FROM {vs} s WHERE s.release_day = @day AND s.{V['id']} = t.{V['id']});",
          f"    INSERT INTO {vn} ({vc}) SELECT {vc} FROM {vs} WHERE release_day = @day;",
          f"    SELECT @day AS released_day, (SELECT COUNT(*) FROM {en}) AS {E['src']}, (SELECT COUNT(*) FROM {vn}) AS {V['src']};",
          "END;", "GO"]
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------------------------------ MLV preview
def mlv_sql(p, doc, g):
    plan = g.build_mlv_plan(doc["ingestion_object"], doc["column_map"], doc["dq_rule"], doc["gold_transform"])
    cdf = g.enable_cdf_sql(doc["ingestion_object"]) + ["ALTER TABLE meta.setting SET TBLPROPERTIES (delta.enableChangeDataFeed = true)"]
    schemas = sorted({g.MLV_SCHEMAS[i["layer"]] for i in plan["items"]})
    parts = [f"-- {p['org']} ({p['industry']}): materialized lake views generated from config/{p['id']}.json.\n"
             "-- This is a preview. nb_mdf_50_mlv_build generates and runs the same DDL against your real Bronze schema.\n"
             "-- Order matters: upstream views first. Every view uses CREATE OR REPLACE, so re-running is safe.",
             "\n".join(f"CREATE SCHEMA IF NOT EXISTS {s};" for s in schemas),
             "-- Change Data Feed on every source so optimal refresh can choose incremental\n" + ";\n".join(cdf) + ";"]
    parts += [it["ddl"] + ";" for it in plan["items"]]
    return "\n\n".join(parts) + "\n", plan


# ------------------------------------------------------------------------------------------ notebooks
def set_cell(nb_rel, marker, code):
    """Replace the code cell whose first line starts with `marker`."""
    path = os.path.join(KIT, "notebooks", nb_rel)
    if not os.path.exists(path):
        return False
    with open(path, encoding="utf-8") as f:
        nb = json.load(f)
    for c in nb["cells"]:
        src = "".join(c["source"])
        if c["cell_type"] == "code" and src.startswith(marker):
            c["source"] = code.splitlines(True)
            break
    else:
        raise ValueError(f"marker {marker!r} not found in {nb_rel}")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(nb, f, indent=1, ensure_ascii=False)
    return True


def embed_notebooks(docs):
    cfg = {pid: doc for pid, doc in docs.items()}
    js = json.dumps(cfg, separators=(",", ":"), ensure_ascii=False)
    assert "'''" not in js
    set_cell("nb_mdf_00_setup_framework.ipynb", "EMBEDDED_CONFIG", f"EMBEDDED_CONFIG = json.loads(r'''{js}''')")
    gen = open(os.path.join(HERE, "generate_data.py"), encoding="utf-8").read()
    set_cell("nb_mdf_01_generate_sample_data.ipynb", '"""Synthetic', gen.split('\nif __name__ == "__main__":')[0])
    sqlgen = open(os.path.join(HERE, "mlv_sqlgen.py"), encoding="utf-8").read()
    set_cell("nb_mdf_mlv_sqlgen.ipynb", "import json, re", sqlgen.split("# %%\n", 2)[-1] if sqlgen.startswith("# %%") else sqlgen)
    sim = os.path.join(KIT, "rti", "rti_simulator.py")
    if os.path.exists(sim):
        code = open(sim, encoding="utf-8").read()
        set_cell("nb_rti_01_stream_simulator.ipynb", '"""Real-Time', code.split('\nif __name__ == "__main__":')[0])


def main(only=None):
    packs = kitlib.all_packs()
    if only:
        packs = [p for p in packs if p["id"] in only]
    g = _load_module("mlv_sqlgen")
    docs = {}
    for p in packs:
        doc = build_config(p)
        docs[p["id"]] = doc
        data = generate_data.generate(p)
        write(f"sql/source_db/{p['id']}.sql", source_db_sql(p, data))
        text, plan = mlv_sql(p, doc, g)
        write(f"mlv/sql/{p['id']}.sql", text)
        print(f"{p['id']:14s} config ok | source db ok | mlv {len(plan['items'])} views, gold skipped {[t[1] for t in plan['skipped_gold']]}")
    if not only:
        embed_notebooks({p["id"]: docs[p["id"]] for p in packs})
    else:   # keep the other packs already embedded
        all_docs = {}
        for p in kitlib.all_packs():
            with open(os.path.join(KIT, "config", f"{p['id']}.json"), encoding="utf-8") as f:
                all_docs[p["id"]] = json.load(f)
        embed_notebooks(all_docs)
    for mod_name in ("build_wh", "build_rti", "build_df", "build_ai"):
        mod = _load_module(mod_name)
        if mod:
            for p in packs:
                mod.build(p, KIT)
            print(f"{mod_name}: done")
    stamp = _load_module("stamp_readme")
    if stamp:
        stamp.main(KIT)


if __name__ == "__main__":
    main(sys.argv[1:] or None)
